-- RLS ------------------------------------------------------------------------
alter table public.card_batch_headers enable row level security;
alter table public.card_batch_details enable row level security;

grant usage on schema public to anon, authenticated;
grant select, insert on table public.card_batch_headers to anon, authenticated;
grant select, insert on table public.card_batch_details to anon, authenticated;

-- Read policies
drop policy if exists "CardBatchHeaders read authenticated" on public.card_batch_headers;
create policy "CardBatchHeaders read authenticated"
  on public.card_batch_headers
  for select
  to authenticated
  using (
    exists (
      select 1 from public.user_memberships m
      where m.user_id = auth.uid()
        and m.organization_id = card_batch_headers.organization_id
        and (m.location_id is null or m.location_id = card_batch_headers.location_id)
    )
  );

drop policy if exists "CardBatchHeaders read anon" on public.card_batch_headers;
create policy "CardBatchHeaders read anon"
  on public.card_batch_headers
  for select
  to anon
  using (
    public.is_valid_location_scope(card_batch_headers.organization_id, card_batch_headers.location_id)
  );

drop policy if exists "CardBatchDetails read authenticated" on public.card_batch_details;
create policy "CardBatchDetails read authenticated"
  on public.card_batch_details
  for select
  to authenticated
  using (
    exists (
      select 1 from public.user_memberships m
      where m.user_id = auth.uid()
        and m.organization_id = card_batch_details.organization_id
        and (m.location_id is null or m.location_id = card_batch_details.location_id)
