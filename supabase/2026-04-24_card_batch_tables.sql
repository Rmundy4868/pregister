-- 2026-04-24  Card Batch Header/Detail Ledger
-- =============================================================================
-- Purpose:
--   Store processor close-batch results in first-class tables instead of JSON
--   snapshots inside transactions.message.
--
-- Tables:
--   public.card_batch_headers
--   public.card_batch_details
-- =============================================================================

create table if not exists public.card_batch_headers (
  id uuid primary key default gen_random_uuid(),
  batch_number bigint generated by default as identity,
  organization_id uuid not null,
  location_id uuid not null,
  terminal_id uuid,
  accepted boolean not null default false,
  processor_status text not null default '',
  processor_message text not null default '',
  terminal_name text not null default '',
  location_name text not null default '',
  organization_name text not null default '',
  organization_number text,
  closed_at timestamptz not null default timezone('utc', now()),
  transaction_count integer not null default 0,
  approved_count integer not null default 0,
  voided_count integer not null default 0,
  original_total numeric(12,2) not null default 0,
  tip_total numeric(12,2) not null default 0,
  final_total numeric(12,2) not null default 0,
  total_amount numeric(12,2) not null default 0,
  integrity_status text not null default '',
  integrity_summary text not null default '',
  processor_close_raw text,
  created_at timestamptz not null default timezone('utc', now())
);

create unique index if not exists idx_card_batch_headers_batch_number
  on public.card_batch_headers (batch_number);

create index if not exists idx_card_batch_headers_org_loc_closed
  on public.card_batch_headers (organization_id, location_id, closed_at desc);

create index if not exists idx_card_batch_headers_terminal_closed
  on public.card_batch_headers (terminal_id, closed_at desc)
  where terminal_id is not null;

-- Optional FK if terminals table exists and terminal_id is used.
do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'card_batch_headers_terminal_id_fkey'
  ) then
    alter table public.card_batch_headers
      add constraint card_batch_headers_terminal_id_fkey
      foreign key (terminal_id)
      references public.terminals (id)
      on delete set null;
  end if;
end $$;

create table if not exists public.card_batch_details (
  id uuid primary key default gen_random_uuid(),
  card_batch_header_id uuid not null
    references public.card_batch_headers (id) on delete cascade,
  organization_id uuid not null,
  location_id uuid not null,
  transaction_detail_id uuid,
  transaction_header_id uuid,
  reference_id text,
  amount numeric(12,2) not null default 0,
  card_type text,
  card_last4 text,
  auth_code text,
  status text not null default '',
  close_status text not null default '',
  integrity_status text not null default '',
  integrity_summary text not null default '',
  processor_reference_id text,
  processor_transaction_type text,
  created_at timestamptz not null default timezone('utc', now())
);

